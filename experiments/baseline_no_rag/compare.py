"""Render two annotated runs of the question set side by side.

V3 step 9: the V1 baseline (no retrieval) against a RAG run. Same rules as
review.py — it reads ``results/`` and ``annotations/``, writes a generated
sheet to ``reviews/``, and never re-asks the model. The join key is the
question id; the order is the question set's.
"""

import argparse
import sys
from typing import Any

from experiments.baseline_no_rag.review import (
    ANNOTATIONS_DIR,
    FLAGS,
    QUESTIONS_FILE,
    RESULTS_DIR,
    REVIEWS_DIR,
    VERDICTS,
    load_json,
    quote,
)

Run = tuple[dict[str, Any], dict[str, Any]]
"""One run: its results file and its annotations (``{}`` if unannotated)."""


def _note(run: Run, qid: str) -> dict[str, Any]:
    """The annotation for one question, validated against the vocabulary."""
    note: dict[str, Any] = run[1].get("annotations", {}).get(qid, {})
    verdict = note.get("verdict", "unscored")
    if verdict not in VERDICTS:
        raise ValueError(f"{qid}: unknown verdict {verdict!r}")
    for flag in note.get("flags", []):
        if flag not in FLAGS:
            raise ValueError(f"{qid}: unknown flag {flag!r}")
    return note


def _tally(run: Run, ids: list[str]) -> str:
    """One line of verdict counts, in VERDICTS order, over the given ids."""
    counts: dict[str, int] = {}
    for qid in ids:
        verdict = _note(run, qid).get("verdict", "unscored")
        counts[verdict] = counts.get(verdict, 0) + 1
    return " · ".join(
        f"{VERDICTS[key]} {counts[key]}" for key in VERDICTS if key in counts
    )


def _section(label: str, run: Run, qid: str) -> list[str]:
    """One run's answer to one question: verdict, answer, sources, flags, note."""
    answers = {record["id"]: record for record in run[0]["answers"]}
    if qid not in answers:
        return ["", f"### {label} — not asked in this run"]
    record = answers[qid]
    note = _note(run, qid)
    lines = [
        "",
        f"### {label} — {VERDICTS[note.get('verdict', 'unscored')]}",
        "",
        quote(record.get("answer", f"[{record.get('error', 'no answer')}]")),
    ]
    sources = record.get("sources", [])
    if sources:
        lines += ["", "**Sources.** " + " · ".join(f"`{one}`" for one in sources)]
    if note.get("flags"):
        lines += ["", "**Flags.** " + ", ".join(f"`{f}`" for f in note["flags"])]
    if note.get("note"):
        lines += ["", f"**Note.** {note['note']}"]
    return lines


def render(baseline: Run, rag: Run, questions: dict[str, Any], name: str) -> str:
    """Build the comparison sheet. Pure string work — no files, no clock."""
    for run in (baseline, rag):
        if run[0]["run"]["set_version"] != questions["set_version"]:
            raise ValueError(
                f"run is set {run[0]['run']['set_version']!r}, "
                f"questions.json is {questions['set_version']!r}"
            )
    ids = [question["id"] for question in questions["questions"]]

    def verdict(run: Run, qid: str) -> str:
        return VERDICTS[_note(run, qid).get("verdict", "unscored")]

    lines = [
        f"# Comparison — {name}",
        "",
        "> Generated from `results/` + `annotations/`. **Do not edit this file.**",
        "",
        f"- **Question set** `{questions['set_version']}`",
        f"- **V1** retrieval {baseline[0]['run']['retrieval']}"
        f" · run {baseline[0]['run']['started_at']}",
        f"- **RAG** retrieval {rag[0]['run']['retrieval']}"
        f" · run {rag[0]['run']['started_at']}",
        "",
        "## Summary",
        "",
        "| id | V1 | RAG |",
        "| --- | --- | --- |",
        *(f"| {qid} | {verdict(baseline, qid)} | {verdict(rag, qid)} |" for qid in ids),
        "",
        f"**V1:** {_tally(baseline, ids)}",
        "",
        f"**RAG:** {_tally(rag, ids)}",
    ]
    for question in questions["questions"]:
        qid = question["id"]
        lines += [
            "",
            "---",
            "",
            f"## {qid}",
            "",
            f"**Ερώτηση.** {question['text']}",
            "",
            f"**Expected.** {question['expected']}",
            *_section("V1", baseline, qid),
            *_section("RAG", rag, qid),
        ]
    return "\n".join(lines) + "\n"


def _load(stem: str) -> Run:
    """A results file and its annotations, by timestamp stem."""
    path = RESULTS_DIR / f"{stem}.json"
    if not path.exists():
        raise FileNotFoundError(f"no such run: {path}")
    annotations = ANNOTATIONS_DIR / path.name
    return load_json(path), load_json(annotations) if annotations.exists() else {}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="compare",
        description="Render a V1 run and a RAG run of the same set side by side.",
    )
    parser.add_argument("baseline", metavar="V1_STEM", help="The no-retrieval run.")
    parser.add_argument("rag", metavar="RAG_STEM", help="The RAG run.")
    args = parser.parse_args(argv)

    try:
        baseline, rag = _load(args.baseline), _load(args.rag)
    except FileNotFoundError as error:
        parser.error(str(error))

    name = f"{args.baseline}-vs-{args.rag}"
    sheet = render(baseline, rag, load_json(QUESTIONS_FILE), name)

    REVIEWS_DIR.mkdir(exist_ok=True)
    out = REVIEWS_DIR / f"compare-{name}.md"
    out.write_text(sheet, encoding="utf-8")
    print(f"Wrote {out}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
