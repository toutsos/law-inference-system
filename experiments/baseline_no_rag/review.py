"""Render a baseline run into a Markdown review sheet.

Three artifacts, three rules:

* ``results/`` is written by ``run.py`` and never edited by hand — it is the
  measurement, and the moment it is editable "the model said this" and "I judged
  the model wrong" stop being distinguishable.
* ``annotations/`` is written by hand — the judgement *about* a run, keyed by
  question id, so a run can be re-scored without reopening what was said.
* ``reviews/`` is generated from the two and never edited at all.

The join key is the question id. Nothing here re-asks the model.
"""

import argparse
import json
import sys
from pathlib import Path
from typing import Any

HERE = Path(__file__).parent
QUESTIONS_FILE = HERE / "questions.json"
RESULTS_DIR = HERE / "results"
ANNOTATIONS_DIR = HERE / "annotations"
REVIEWS_DIR = HERE / "reviews"

VERDICTS = {
    "correct": "✅ correct",
    "partially_correct": "🟡 partially correct",
    "fabricated": "❌ fabricated citation",
    "refused_with_fabrication": "❌ refused, fabricated anyway",
    "refused": "⚠️ refused",
    "vague": "⚪ vague, no citation",
    "unscored": "— not scored",
}

FLAGS = {
    "denies_law_exists": "asserts the law does not exist or is unpublished",
    "role_dodge": "claims the question is outside its role",
    "self_contradiction": "contradicts itself within one answer",
    "accidental_correct_token": "a correct detail inside a fabricated answer",
    "misreads_question": "misquotes the question it was given",
    "unmeasured_probe": "failed earlier than the probe could measure",
}


def load_json(path: Path) -> dict[str, Any]:
    """Read one JSON file. Greek text, so the encoding is stated, not guessed."""
    data: dict[str, Any] = json.loads(path.read_text(encoding="utf-8"))
    return data


def latest_run(results_dir: Path) -> Path:
    """The most recent results file. Timestamps sort lexically, so this is max()."""
    runs = sorted(results_dir.glob("*.json"))
    if not runs:
        raise FileNotFoundError(f"no runs in {results_dir}")
    return runs[-1]


def _quote(text: str) -> str:
    """Blockquote a multi-line answer so Markdown keeps it as one unit."""
    return "\n".join(f"> {line}" if line else ">" for line in text.splitlines())


def render(
    result: dict[str, Any],
    questions: dict[str, Any],
    annotations: dict[str, Any],
    name: str,
) -> str:
    """Build the review sheet. Pure string work — no files, no clock, no network."""
    run = result["run"]
    source = questions["source"]
    expected = {q["id"]: q for q in questions["questions"]}
    scored = annotations.get("annotations", {})

    lines = [
        f"# Baseline review — {name}",
        "",
        "> Generated from `results/` + `annotations/`. **Do not edit this file** —",
        "> edit the annotation file and re-render.",
        "",
        f"- **Law** {source['law']}, ΦΕΚ {source['fek']} — `{source['corpus_document_id']}`",
        f"- **Question set** `{run['set_version']}` · **retrieval** {run['retrieval']}",
        f"- **Model requested** `{run['model_requested']}` at {run['base_url']}",
        f"- **Run** {run['started_at']} → {run['finished_at']}",
        "",
        "## Summary",
        "",
        "| id | verdict | flags | tokens out | seconds |",
        "| --- | --- | --- | ---: | ---: |",
    ]

    tally: dict[str, int] = {}
    flag_tally: dict[str, int] = {}
    for answer in result["answers"]:
        note = scored.get(answer["id"], {})
        verdict = note.get("verdict", "unscored")
        if verdict not in VERDICTS:
            raise ValueError(f"{answer['id']}: unknown verdict {verdict!r}")
        tally[verdict] = tally.get(verdict, 0) + 1
        flags = note.get("flags", [])
        for flag in flags:
            if flag not in FLAGS:
                raise ValueError(f"{answer['id']}: unknown flag {flag!r}")
            flag_tally[flag] = flag_tally.get(flag, 0) + 1
        lines.append(
            f"| {answer['id']} | {VERDICTS[verdict]} | {', '.join(flags) or '—'} "
            f"| {answer.get('tokens_out', '—')} | {answer.get('duration_seconds', '—')} |"
        )

    lines += [
        "",
        "**Verdicts:** "
        + " · ".join(
            f"{VERDICTS[key]} {count}" for key, count in sorted(tally.items())
        ),
    ]
    if flag_tally:
        lines += [
            "",
            "**Flags:** "
            + " · ".join(
                f"`{key}` {count} — {FLAGS[key]}"
                for key, count in sorted(flag_tally.items())
            ),
        ]

    for answer in result["answers"]:
        question = expected[answer["id"]]
        note = scored.get(answer["id"], {})
        verdict = note.get("verdict", "unscored")
        lines += [
            "",
            "---",
            "",
            f"## {answer['id']} — {VERDICTS[verdict]}",
            "",
            f"**Ερώτηση.** {answer['question']}",
            "",
            f"**Probes.** {answer['probes']}",
            "",
            f"**Expected.** {question['expected']}",
            "",
            "**Answer.**",
            "",
            _quote(answer.get("answer", f"[{answer.get('error', 'no answer')}]")),
        ]
        cited = note.get("cited", [])
        if cited:
            lines += ["", "**Cited.** " + " · ".join(f"`{one}`" for one in cited)]
        if note.get("note"):
            lines += ["", f"**Note.** {note['note']}"]

    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="review",
        description="Render a baseline run and its annotations into Markdown.",
    )
    parser.add_argument(
        "--run",
        metavar="STEM",
        help="Results file stem (default: the most recent run).",
    )
    args = parser.parse_args(argv)

    path = RESULTS_DIR / f"{args.run}.json" if args.run else latest_run(RESULTS_DIR)
    if not path.exists():
        parser.error(f"no such run: {path}")

    annotations_file = ANNOTATIONS_DIR / path.name
    annotations = load_json(annotations_file) if annotations_file.exists() else {}
    if not annotations:
        print(
            f"No annotations at {annotations_file} — rendering unscored.",
            file=sys.stderr,
        )

    sheet = render(load_json(path), load_json(QUESTIONS_FILE), annotations, path.stem)

    REVIEWS_DIR.mkdir(exist_ok=True)
    out = REVIEWS_DIR / f"{path.stem}.md"
    out.write_text(sheet, encoding="utf-8")
    print(f"Wrote {out}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
